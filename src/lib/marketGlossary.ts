export type GlossaryKey = keyof typeof MARKET_GLOSSARY

// 後端判讀標籤的 key（signals.js）對應到說明；沒有對應的略過
export function signalGlossaryKeys(signals: { key: string }[]): GlossaryKey[] {
  const keys = signals.map((s) => s.key).filter((key): key is GlossaryKey => key in MARKET_GLOSSARY)
  return [...new Set(keys)]
}
